#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const marker = '<!-- generated by .agents/scripts/sync-claude-skill-adapters.mjs; do not edit -->';
const oldMarkers = [
  '<!-- adapter: workflow lives in canonical skill -->',
];
const root = await fs.realpath(fileURLToPath(new URL('../../', import.meta.url)));
const canonicalRoot = path.join(root, '.agents', 'skills');
const adapterRoot = path.join(root, '.claude', 'skills');
const maxSkills = 256;
const maxBytes = 4 * 1024 * 1024;

async function localDirectory(parts, { create = false, missing = false } = {}) {
  let current = root;
  for (const name of parts) {
    current = path.join(current, name);
    let stat;
    try {
      stat = await fs.lstat(current);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      if (!create) {
        if (missing) return null;
        throw error;
      }
      await fs.mkdir(current);
      stat = await fs.lstat(current);
    }
    if (!stat.isDirectory() || stat.isSymbolicLink()) {
      throw new Error(`${parts.slice(0, parts.indexOf(name) + 1).join('/')} must be a local directory.`);
    }
    const resolved = await fs.realpath(current);
    const relative = path.relative(root, resolved);
    if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
      throw new Error(`${path.relative(root, current)} escapes the repository.`);
    }
  }
  return current;
}

async function plainDirectories(parent, label) {
  const stat = await fs.lstat(parent);
  if (!stat.isDirectory() || stat.isSymbolicLink()) throw new Error(`${label} must be a local directory.`);
  const result = [];
  for (const name of (await fs.readdir(parent)).sort()) {
    const directory = path.join(parent, name);
    const child = await fs.lstat(directory);
    if (!child.isDirectory() || child.isSymbolicLink()) throw new Error(`${label}/${name} must be a local directory.`);
    result.push({ name, directory });
  }
  return result;
}

function frontmatter(source, relative) {
  const normalized = source.replace(/^\uFEFF/, '').replaceAll('\r\n', '\n');
  const match = normalized.match(/^---\n[\s\S]*?\n---(?:\n|$)/);
  if (!match) throw new Error(`${relative} has no YAML frontmatter.`);
  return match[0].replace(/\n+$/, '') + '\n';
}

function expectedAdapter(name, source) {
  const canonical = `../../../.agents/skills/${name}`;
  return `${frontmatter(source, `.agents/skills/${name}/SKILL.md`)}\n${marker}\n\nRead \`${canonical}/SKILL.md\` completely and follow that canonical workflow. Do not recursively invoke this adapter name.\n`;
}

async function canonicalAdapters() {
  const result = new Map();
  let bytes = 0;
  await localDirectory(['.agents']);
  await localDirectory(['.agents', 'skills']);
  for (const { name, directory } of await plainDirectories(canonicalRoot, '.agents/skills')) {
    if (result.size >= maxSkills) throw new Error(`Skill count exceeds the ${maxSkills} skill limit.`);
    const skill = path.join(directory, 'SKILL.md');
    const stat = await fs.lstat(skill).catch(() => null);
    if (!stat?.isFile() || stat.isSymbolicLink()) throw new Error(`.agents/skills/${name}/SKILL.md must be a local file.`);
    bytes += stat.size;
    if (bytes > maxBytes) throw new Error(`Skill metadata exceeds the ${maxBytes} byte limit.`);
    result.set(name, expectedAdapter(name, await fs.readFile(skill, 'utf8')));
  }
  return result;
}

async function atomicWrite(file, content) {
  const temporary = path.join(path.dirname(file), `.SKILL.md.${randomUUID()}.tmp`);
  try {
    await fs.writeFile(temporary, content, { encoding: 'utf8', flag: 'wx', mode: 0o600 });
    await fs.rename(temporary, file);
  } finally {
    await fs.unlink(temporary).catch(() => {});
  }
}

async function main() {
  const mode = process.argv[2];
  if (!['--check', '--write'].includes(mode) || process.argv.length !== 3) {
    throw new Error('Usage: node .agents/scripts/sync-claude-skill-adapters.mjs --check|--write');
  }
  const write = mode === '--write';
  const canonical = await canonicalAdapters();
  const existingAdapterRoot = await localDirectory(['.claude', 'skills'], { missing: true });
  if (write && !existingAdapterRoot) await localDirectory(['.claude', 'skills'], { create: true });
  const drift = [];

  const adapterDirectories = existingAdapterRoot ? await plainDirectories(adapterRoot, '.claude/skills') : [];
  if (adapterDirectories.length > maxSkills) throw new Error(`Claude adapter count exceeds the ${maxSkills} skill limit.`);
  for (const { name, directory } of adapterDirectories) {
    const entries = await fs.readdir(directory);
    const file = path.join(directory, 'SKILL.md');
    const content = entries.length === 1 && entries[0] === 'SKILL.md' ? await fs.readFile(file, 'utf8') : '';
    if (canonical.has(name)) continue;
    if (![marker, ...oldMarkers].some((item) => content.includes(item))) {
      throw new Error(`Refusing to remove unmanaged Claude skill adapter: .claude/skills/${name}`);
    }
    drift.push(`stale:${name}`);
    if (write) {
      await fs.unlink(file);
      await fs.rmdir(directory);
    }
  }

  for (const [name, expected] of canonical) {
    const directory = path.join(adapterRoot, name);
    const file = path.join(directory, 'SKILL.md');
    const fileStat = await fs.lstat(file).catch((error) => error.code === 'ENOENT' ? null : Promise.reject(error));
    if (fileStat && (!fileStat.isFile() || fileStat.isSymbolicLink())) {
      throw new Error(`.claude/skills/${name}/SKILL.md must be a local file.`);
    }
    const actual = fileStat ? await fs.readFile(file, 'utf8') : null;
    if (actual === expected) continue;
    drift.push(`${actual === null ? 'missing' : 'changed'}:${name}`);
    if (write) {
      await localDirectory(['.claude', 'skills', name], { create: true });
      await atomicWrite(file, expected);
    }
  }

  if (drift.length && !write) throw new Error(`Claude skill adapters are out of date (${drift.join(', ')}).`);
  console.log(`${canonical.size} Claude skill adapters ${write ? 'synchronized' : 'verified'}.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
